CREATE TABLE atendimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    modalidade VARCHAR(31) NOT NULL,
    paciente_id BIGINT NOT NULL CHECK (paciente_id > 0),
    profissional_id BIGINT NOT NULL CHECK (profissional_id > 0),
    inicio_previsto TIMESTAMP NOT NULL,
    motivo VARCHAR(1000) NOT NULL,
    observacoes VARCHAR(4000),
    situacao VARCHAR(30) NOT NULL,
    inicio_efetivo TIMESTAMP,
    fim_efetivo TIMESTAMP,
    encaminhamento VARCHAR(120),
    especialidade VARCHAR(120),
    prioridade VARCHAR(20),
    tipo_cirurgia VARCHAR(120),
    observacoes_pre_operatorias VARCHAR(4000),
    observacoes_pos_operatorias VARCHAR(4000),
    CHECK (fim_efetivo IS NULL OR (inicio_efetivo IS NOT NULL AND fim_efetivo >= inicio_efetivo))
);
CREATE INDEX idx_atendimento_paciente ON atendimento(paciente_id, inicio_previsto);
