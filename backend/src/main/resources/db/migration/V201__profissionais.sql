CREATE TABLE profissional_saude (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    nome VARCHAR(120) NOT NULL,
    registro_profissional VARCHAR(60) NOT NULL,
    categoria VARCHAR(20) NOT NULL,
    especialidade VARCHAR(120) NOT NULL,
    area_cirurgica VARCHAR(120),
    telefone VARCHAR(30) NOT NULL,
    email VARCHAR(254) NOT NULL,
    CONSTRAINT uk_profissional_registro UNIQUE (registro_profissional),
    CONSTRAINT ck_profissional_categoria CHECK (categoria IN ('CLINICO_GERAL', 'ESPECIALISTA', 'CIRURGIAO')),
    CONSTRAINT ck_profissional_area_cirurgica CHECK (
        (categoria = 'CIRURGIAO' AND area_cirurgica IS NOT NULL AND TRIM(area_cirurgica) <> '')
        OR (categoria <> 'CIRURGIAO' AND area_cirurgica IS NULL)
    )
);
