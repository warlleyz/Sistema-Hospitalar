CREATE TABLE internacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    paciente_id BIGINT NOT NULL CHECK (paciente_id > 0),
    profissional_id BIGINT NOT NULL CHECK (profissional_id > 0),
    quarto_id BIGINT NOT NULL REFERENCES quarto(id),
    data_entrada DATE NOT NULL,
    data_prevista_alta DATE,
    data_alta_efetiva DATE,
    observacoes VARCHAR(4000),
    CONSTRAINT ck_internacao_previsao CHECK (data_prevista_alta IS NULL OR data_prevista_alta >= data_entrada),
    CONSTRAINT ck_internacao_alta CHECK (data_alta_efetiva IS NULL OR data_alta_efetiva >= data_entrada)
);
CREATE INDEX idx_internacao_quarto_ativa ON internacao(quarto_id, data_alta_efetiva);
CREATE INDEX idx_internacao_paciente ON internacao(paciente_id, data_entrada);
